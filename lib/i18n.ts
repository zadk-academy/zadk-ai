export function fmt(lang: Lang, n: number, digits = 0) {
  return new Intl.NumberFormat(lang === "ar" ? "ar-SA-u-nu-arab" : "en-SA", {
    maximumFractionDigits: digits,
  }).format(n);
}

/** Reads Arabic or Western digits typed by the user. */
export function toNumber(s: string) {
  const western = s.replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d))).replace(/[^\d.]/g, "");
  return Number(western);
}

